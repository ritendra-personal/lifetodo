const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=readFileSync('public/app.js','utf8');
const start=source.indexOf('function renderYearCalendar(');
const end=source.indexOf('\n}',start)+2;
const context={state:{events:[{id:'test',title:'Film <shoot>'}]},els:{taskList:{innerHTML:''}},Date,localDateKey:day=>[day.getFullYear(),String(day.getMonth()+1).padStart(2,'0'),String(day.getDate()).padStart(2,'0')].join('-'),eventOccursOnDay:(_,day)=>day.getMonth()===1&&[28,29].includes(day.getDate()),eventSort:()=>0,escapeHtml:text=>String(text).replaceAll('<','&lt;').replaceAll('>','&gt;')};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
context.renderYearCalendar(2024);
let html=context.els.taskList.innerHTML;
assert.equal((html.match(/class="year-month"/g)||[]).length,12);
assert.equal((html.match(/data-calendar-add-date=/g)||[]).length,366);
assert.ok(html.includes('2024-02-29'));
assert.equal((html.match(/data-event-id="test"/g)||[]).length,2);
assert.ok(html.includes('Film &lt;shoot&gt;'));
context.renderYearCalendar(2025);
html=context.els.taskList.innerHTML;
assert.equal((html.match(/data-calendar-add-date=/g)||[]).length,365);
assert.ok(!html.includes('2025-02-29'));
console.log('Year calendar: twelve months, leap dates, multi-day events, and escaped titles pass.');
