export function expandDiscovery(items) {
 for (const topic of items) {
  if (topic.group || (topic.kind && topic.kind !== 'learning-discovery') || ['check:admin:passport','check:admin:real-id','check:admin:oci'].includes(topic.id)) continue;
  const parts=topic.id.split(':');
  const choices=topic.id==='check:admin:residency'?['Visa','Residency permit','Citizenship application','Travel authorization']:discoveryChoices[parts[1]]?.[Number(parts[2])];
  if(topic.id==='check:admin:family-documents'){topic.kind='support-discovery';topic.title='Help someone with their documents';continue;}
  topic.kind='outcome-discovery';topic.expandedDiscovery=true;
  topic.choices=choices?.length?choices:['Arrange or start this','Update or improve this','Maintain what is working'];
 }
 const appointments=items.find(t=>t.id==='check:health:0');
 appointments.kind=null;appointments.group='appointments';appointments.question='What kind of appointment or care do you want to arrange?';
 const types=[['primary','Primary care'],['dental','Dental care'],['vision','Eye care'],['mental','Mental health support'],['specialist','A specialist'],['hearing','Hearing care'],['reproductive','Reproductive care'],['rehabilitation','Rehabilitation or physical therapy'],['preventive','Screening or preventive care'],['other','Something else']];
 for(const [slug,title] of types)items.push({id:'appointment:'+slug,parent:appointments.id,area:appointments.area,title,kind:'outcome-discovery',choices:slug==='dental'?dentalChoices:slug==='other'?[]:[['Arrange a visit',`Have my ${title.toLowerCase()} appointment arranged`],['Follow up on existing care',`Complete my ${title.toLowerCase()} follow-up`]],expandedDiscovery:true});
 items.push({id:'care:dental',parent:'check:health:4',area:appointments.area,title:'Dental and gum care',kind:'outcome-discovery',choices:dentalChoices,expandedDiscovery:true});
 // Expand common choices into actual branches, so a selected choice is also
 // represented in the map rather than being lost after filling a text field.
 const choiceNodes=[];
 for(const topic of items.filter(t=>t.kind==='outcome-discovery'&&t.choices?.length)){
  topic.kind=null;topic.group='discovery';topic.question='What would you like to address?';
  [...topic.choices,'Something else'].forEach((choice,index)=>{
   const [title,preset,action]=Array.isArray(choice)?choice:[choice,'',topic.action];
   choiceNodes.push({id:topic.id+':choice:'+index,parent:topic.id,area:topic.area,title,preset,action:action||topic.action,kind:'outcome-discovery',choices:[],expandedDiscovery:true});
  });
 }
 const supplemental=supplementalChoices.filter(([parent])=>items.some(topic=>topic.id===parent)).map(([parent,slug,title])=>{
  const topic=items.find(item=>item.id===parent);
  return {id:parent+':extra:'+slug,parent,area:topic.area,title,kind:'outcome-discovery',choices:[],expandedDiscovery:true,action:topic.action};
 });
 return [...items,...choiceNodes,...supplemental];
}

// Preserve old reviewed topics and links at their original IDs as explicit outcomes.
// Their replacement discovery menu gets a new ID; nothing is written or deleted here.
export function assembleTopics(base, templates, data) {
 const replaced=new Map(templates.filter(t=>t.expandedDiscovery&&data.answers?.[t.id]?.status!=='uninterested'&&(data.answers?.[t.id]?.status||(data.links?.[t.id]||[]).length)).map(t=>[t.id,'discover:'+t.id]));
 const menus=templates.map(t=>({...t,id:replaced.get(t.id)||t.id,parent:replaced.get(t.parent)||t.parent}));
 const saved=templates.filter(t=>replaced.has(t.id)).map(t=>({...t,kind:null,group:null,expandedDiscovery:false,choices:null,suggested:false,parent:replaced.get(t.id),question:`Where are you with “${t.title}”?`}));
 const concerns=(data.concerns||[]).map(topic=>{
  const original=topic.parent?.startsWith('discover:')?topic.parent.slice(9):null;
  return original&&templates.some(item=>item.id===original)&&!replaced.has(original)?{...topic,parent:original}:topic;
 });
 return [...base,...menus,...saved,...concerns];
}
